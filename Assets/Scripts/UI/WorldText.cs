using UnityEngine;
using UnityEngine.SceneManagement;

namespace Voss.UI
{
    /// <summary>One-sided, depth-tested lettering. Keeps dynamic font atlases and card layout in sync.</summary>
    [ExecuteAlways, RequireComponent(typeof(TextMesh), typeof(MeshRenderer))]
    public class WorldText : MonoBehaviour
    {
        [SerializeField] private Vector2 maxSize;
        [SerializeField] private float preferredCharacterSize;
        private TextMesh textMesh;
        private MeshRenderer textRenderer;
        private MaterialPropertyBlock properties;
        private string lastText;
        private bool needsRefresh;

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
        private static void RegisterScenes()
        {
            SceneManager.sceneLoaded -= UpgradeScene;
            SceneManager.sceneLoaded += UpgradeScene;
        }

        // Supports existing saved scenes as well as scenes generated by the editor builders.
        private static void UpgradeScene(Scene scene, LoadSceneMode mode)
        {
            foreach (var root in scene.GetRootGameObjects())
                foreach (var text in root.GetComponentsInChildren<TextMesh>(true))
                    if (text.GetComponent<WorldText>() == null) text.gameObject.AddComponent<WorldText>();
        }

        private void OnEnable()
        {
            textMesh = GetComponent<TextMesh>();
            textRenderer = GetComponent<MeshRenderer>();
            properties = new MaterialPropertyBlock();
            if (preferredCharacterSize <= 0f) preferredCharacterSize = textMesh.characterSize;
            var material = Resources.Load<Material>("WorldText");
            if (material != null) textRenderer.sharedMaterial = material;
            if (maxSize == Vector2.zero) FindCardBounds();
            Font.textureRebuilt += OnFontRebuilt;
            Refresh();
        }

        private void OnDisable() { Font.textureRebuilt -= OnFontRebuilt; }

        private void OnFontRebuilt(Font font)
        {
            if (textMesh != null && font == textMesh.font) needsRefresh = true;
        }

        private void LateUpdate()
        {
            if (needsRefresh || textMesh.text != lastText) Refresh();
        }

        public void FitWithin(Vector2 size)
        {
            maxSize = size;
            if (textMesh == null) textMesh = GetComponent<TextMesh>();
            if (textRenderer == null) textRenderer = GetComponent<MeshRenderer>();
            if (preferredCharacterSize <= 0f) preferredCharacterSize = textMesh.characterSize;
            Refresh();
        }

        private void FindCardBounds()
        {
            if (transform.parent == null) return;
            foreach (Transform sibling in transform.parent)
            {
                if (sibling.name != "TicketCard" && sibling.name != "CardBody" &&
                    sibling.name != "Plate" && sibling.name != "ScreenBody") continue;
                var body = sibling.GetComponent<MeshRenderer>();
                if (body == null) continue;
                var bounds = body.localBounds;
                var projected = new Bounds();
                bool first = true;
                for (int x = -1; x <= 1; x += 2)
                    for (int y = -1; y <= 1; y += 2)
                        for (int z = -1; z <= 1; z += 2)
                        {
                            Vector3 corner = bounds.center + Vector3.Scale(bounds.extents, new Vector3(x, y, z));
                            corner = transform.InverseTransformPoint(sibling.TransformPoint(corner));
                            if (first) { projected = new Bounds(corner, Vector3.zero); first = false; }
                            else projected.Encapsulate(corner);
                        }
                maxSize = new Vector2(projected.size.x * 0.88f, projected.size.y * 0.8f);
                return;
            }
        }

        private void Refresh()
        {
            needsRefresh = false;
            lastText = textMesh.text;
            if (textMesh.font != null)
            {
                textMesh.font.RequestCharactersInTexture(textMesh.text, textMesh.fontSize, textMesh.fontStyle);
                if (properties == null) properties = new MaterialPropertyBlock();
                textRenderer.GetPropertyBlock(properties);
                properties.SetTexture("_MainTex", textMesh.font.material.mainTexture);
                textRenderer.SetPropertyBlock(properties);
            }

            if (maxSize.x <= 0f || maxSize.y <= 0f || string.IsNullOrEmpty(lastText)) return;
            textMesh.characterSize = preferredCharacterSize;
            Vector3 size = textRenderer.localBounds.size;
            float fit = Mathf.Min(1f, maxSize.x / Mathf.Max(size.x, 0.0001f),
                maxSize.y / Mathf.Max(size.y, 0.0001f));
            textMesh.characterSize = preferredCharacterSize * fit;
        }
    }
}
